    Mesh Mesh::CreateCube()
    {


        std::vector<Vertex> vertices =
        {

            // Front face

            {{-0.5f,-0.5f, 0.5f},{1,1,1},{0,0}},
            {{ 0.5f,-0.5f, 0.5f},{1,1,1},{1,0}},
            {{ 0.5f, 0.5f, 0.5f},{1,1,1},{1,1}},
            {{-0.5f, 0.5f, 0.5f},{1,1,1},{0,1}},


            // Back face

            {{ 0.5f,-0.5f,-0.5f},{1,1,1},{0,0}},
            {{-0.5f,-0.5f,-0.5f},{1,1,1},{1,0}},
            {{-0.5f, 0.5f,-0.5f},{1,1,1},{1,1}},
            {{ 0.5f, 0.5f,-0.5f},{1,1,1},{0,1}},


            // Left

            {{-0.5f,-0.5f,-0.5f},{1,1,1},{0,0}},
            {{-0.5f,-0.5f, 0.5f},{1,1,1},{1,0}},
            {{-0.5f, 0.5f, 0.5f},{1,1,1},{1,1}},
            {{-0.5f, 0.5f,-0.5f},{1,1,1},{0,1}},


            // Right

            {{0.5f,-0.5f,0.5f},{1,1,1},{0,0}},
            {{0.5f,-0.5f,-0.5f},{1,1,1},{1,0}},
            {{0.5f,0.5f,-0.5f},{1,1,1},{1,1}},
            {{0.5f,0.5f,0.5f},{1,1,1},{0,1}},


            // Top

            {{-0.5f,0.5f,0.5f},{1,1,1},{0,0}},
            {{0.5f,0.5f,0.5f},{1,1,1},{1,0}},
            {{0.5f,0.5f,-0.5f},{1,1,1},{1,1}},
            {{-0.5f,0.5f,-0.5f},{1,1,1},{0,1}},


            // Bottom

            {{-0.5f,-0.5f,-0.5f},{1,1,1},{0,0}},
            {{0.5f,-0.5f,-0.5f},{1,1,1},{1,0}},
            {{0.5f,-0.5f,0.5f},{1,1,1},{1,1}},
            {{-0.5f,-0.5f,0.5f},{1,1,1},{0,1}}

        };



        std::vector<uint32_t> indices =
        {

            0,1,2,
            2,3,0,

            4,5,6,
            6,7,4,

            8,9,10,
            10,11,8,

            12,13,14,
            14,15,12,

            16,17,18,
            18,19,16,

            20,21,22,
            22,23,20

        };



        return Mesh(
            vertices,
            indices
        );


    }


